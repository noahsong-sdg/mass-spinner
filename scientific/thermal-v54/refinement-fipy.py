"""Actual-FiPy thick-wall refinements with independent passive energy/entropy checks.

Input is generated by refinement-cases.py; no production output is consumed.
The imported oracle's original nonlinear residual gate is unchanged.
Run only in safe-dev with the pinned FiPy/SciPy environment.
"""
from pathlib import Path
import hashlib
import importlib.util
import json
import math
import sys
import numpy as np

ORACLE = Path(__file__).resolve().parents[1] / 'thermal-v53/reference-fipy.py'
spec = importlib.util.spec_from_file_location('thickwall_fipy', ORACLE)
reference = importlib.util.module_from_spec(spec)
spec.loader.exec_module(reference)

# Independent SI transcription; differences are factored before summation.
MOLAR = .18384
A, B, C, D, E = 23.95930, 2.639680e-3, 1.257750e-6, -.254642e-9, -.048407e6


def hchange(new, old):
    d = new - old
    return d * (A + B * (new + old) / 2
                + C * (new*new + new*old + old*old) / 3
                + D * (new**3 + new*new*old + new*old*old + old**3) / 4
                + E / (new*old)) / MOLAR


def schange(new, old):
    d = new - old
    return (A * np.log1p(d / old) + B * d
            + C * d * (new + old) / 2
            + D * d * (new*new + new*old + old*old) / 3
            + E * d * (new + old) / (2 * new*new * old*old)) / MOLAR


def cp(value):
    return (A + B*value + C*value**2 + D*value**3 + E/value**2) / MOLAR


def checks(case, result):
    c = case['config']
    edges = np.linspace(c['radiusM'], c['radiusM'] + c['thicknessM'], c['cells'] + 1)
    masses = 19250 * math.pi * c['lengthM'] * np.diff(edges) * (edges[1:] + edges[:-1])
    initial = np.asarray([case['initial']['gasK'], *case['initial']['wallK']])
    old = initial.copy()
    cg, coolant = c['gasCapacityJK'], c['coolantK']
    scale = 1 + cg*initial[0] + float(np.dot(masses, cp(initial[1:])*initial[1:]))
    cooling_old = 0.
    maximum_energy = 0.
    minimum_entropy = math.inf
    maximum_entropy_budget = 0.
    for state in result['states']:
        new = np.asarray([state['gasK'], *state['wallK']])
        assert np.all(np.isfinite(new)) and np.min(new) >= 500-1e-8 and np.max(new) <= 1000+1e-8
        cooling = state['coolingEnergyJ']
        energy = cg*(new[0]-initial[0]) + float(np.dot(masses, hchange(new[1:], initial[1:]))) + cooling
        maximum_energy = max(maximum_energy, abs(energy)/scale)
        ds = cg*math.log1p((new[0]-old[0])/old[0]) + float(np.dot(masses, schange(new[1:], old[1:])))
        bath = (cooling-cooling_old)/coolant
        budget = 8*np.finfo(float).eps*(1+cg+float(np.dot(masses, cp(new[1:])))+abs(bath))
        assert ds+bath >= -budget, ('Passive entropy decrease', case['name'], ds+bath, budget)
        minimum_entropy = min(minimum_entropy, ds+bath)
        maximum_entropy_budget = max(maximum_entropy_budget, budget)
        old, cooling_old = new, cooling
    assert maximum_energy < 1e-9, ('Independent total energy', case['name'], maximum_energy)
    entropy = cg*math.log1p((old[0]-initial[0])/initial[0]) + float(np.dot(masses, schange(old[1:], initial[1:]))) + cooling_old/coolant
    return {'maximumRelativeEnergyBalance': maximum_energy,
            'minimumEntropyIncrementJK': minimum_entropy,
            'maximumEntropyRoundoffBudgetJK': maximum_entropy_budget,
            'totalEntropyProductionJK': entropy,
            'passiveBoundsK': [500, 1000], 'allPass': True}


def endpoint(result):
    state = result['states'][-1]
    return np.asarray([state['gasK'], *state['wallK']])


def analyze(cases, runs):
    groups = {name: sorted([c for c in cases if c['study']['family'] == name],
                           key=lambda c: c['study']['cells'] if name == 'spatial' else c['study']['steps'])
              for name in ('spatial', 'temporal', 'fast-gas')}
    families = {}
    for family, members in groups.items():
        rows = []
        def centers(c):
            cfg = c['config']
            e = np.linspace(cfg['radiusM'], cfg['radiusM'] + cfg['thicknessM'], cfg['cells'] + 1)
            return np.sqrt(e[:-1]*e[1:])
        fixed_points = np.linspace(centers(members[0])[0], centers(members[0])[-1], 17) if family == 'spatial' else None
        fixed_rows = []
        for a, b in zip(members, members[1:]):
            x, y = endpoint(runs[a['name']]), endpoint(runs[b['name']])
            if family == 'spatial':
                coarse_centers, fine_centers = centers(a), centers(b)
                assert min(coarse_centers) >= min(fine_centers) and max(coarse_centers) <= max(fine_centers), 'No spatial extrapolation'
                projected = np.interp(coarse_centers, fine_centers, y[1:])
                error = max(abs(x[0]-y[0]), float(np.max(np.abs(x[1:]-projected))))
                assert fixed_points[0] >= max(coarse_centers[0], fine_centers[0]) and fixed_points[-1] <= min(coarse_centers[-1], fine_centers[-1]), 'No fixed-radius extrapolation'
                fixed_error = max(abs(x[0]-y[0]), float(np.max(np.abs(np.interp(fixed_points, coarse_centers, x[1:])-np.interp(fixed_points, fine_centers, y[1:])))))
                fixed_rows.append({'coarse': a['name'], 'fine': b['name'], 'maximumEndpointDifferenceK': fixed_error})
            else:
                error = float(np.max(np.abs(x-y)))
            rows.append({'coarse': a['name'], 'fine': b['name'], 'coarseCells': a['config']['cells'], 'maximumEndpointDifferenceK': error})
        errors = [row['maximumEndpointDifferenceK'] for row in rows]
        ratios = [b/a for a, b in zip(errors, errors[1:])]
        # Only measure contraction when both signals are resolved above 1e-8 K.
        failed = [{'coarse': rows[i]['coarse'], 'ratio': ratio} for i, ratio in enumerate(ratios)
                  if min(errors[i:i+2]) > 1e-8 and ratio >= .85]
        families[family] = {'rows': rows, 'differenceRatios': ratios,
                            'resolvedContractionThresholdK': 1e-8,
                            'failedComparisons': failed, 'allGridsContract': not failed,
                            'endpointOnly': True, 'allPass': not failed}
        if family == 'spatial':
            tref = 1000.
            k = 149.441-.045466*tref+13.193e-6*tref**2-1.484e-9*tref**3+3.866e6/tref**2
            alpha = k/(19250*float(cp(tref)))
            penetration = math.sqrt(alpha*members[0]['study']['durationS'])
            resolved = lambda c: c['config']['thicknessM']/c['config']['cells'] <= penetration
            minimum = min(c['config']['cells'] for c in members if resolved(c))
            tail_errors = [r['maximumEndpointDifferenceK'] for r in rows if r['coarseCells'] >= minimum]
            tail_ratios = [b/a for a, b in zip(tail_errors, tail_errors[1:])]
            tail_pass = len(tail_ratios) >= 2 and min(tail_errors) > 1e-8 and all(r < .85 for r in tail_ratios)
            families[family].update({'diffusivityAt1000KM2S': alpha, 'diffusionLengthM': penetration,
                'resolvedMinimumCells': minimum,
                'resolutionCriterion': 'Cell width <= sqrt(alpha(1000 K)*duration)',
                'resolvedTailErrorsK': tail_errors, 'resolvedTailRatios': tail_ratios,
                'resolvedTailContracts': tail_pass,
                'fixedRadiusDiagnostic': {'radiusM': fixed_points.tolist(), 'rows': fixed_rows, 'diagnosticOnly': True}})
        if family == 'fast-gas':
            families[family]['scope'] = 'Temporal endpoint refinement on a fixed discrete wall. This mesh does not establish spatial resolution of the fast solid boundary layer.'
    return families


source, target = map(Path, sys.argv[1:3])
packet = json.loads(source.read_text())
runs, physical = {}, {}
out = {'solver': 'Actual FiPy/SciPy', 'fipyVersion': reference.fipy.__version__,
       'inputSHA256': hashlib.sha256(source.read_bytes()).hexdigest(),
       'scriptSHA256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
       'oracleSHA256': hashlib.sha256(ORACLE.read_bytes()).hexdigest(),
       'cases': runs, 'physicalChecks': physical, 'refinement': {},
       'scope': 'Exact failed case and passive low-inventory refinements. Cross-code agreement is discrete-model agreement, not physical calibration.',
       'allPass': False, 'qualificationPass': False, 'analysisStatus': 'solving'}
for case in packet['cases']:
    result = reference.run_case(case)
    runs[case['name']] = result
    # Preserve each converged result before physical or summary assertions.
    target.write_text(json.dumps(out, separators=(',', ':')) + '\n')
    physical[case['name']] = checks(case, result)
out['analysisStatus'] = 'pending'
target.write_text(json.dumps(out, separators=(',', ':')) + '\n')
out['refinement'] = analyze(packet['cases'], runs)
out['analysisStatus'] = 'complete'
out['allPass'] = all(row['allPass'] for row in out['refinement'].values())
out['qualificationPass'] = (all(row['allPass'] for row in physical.values())
    and out['refinement']['spatial']['resolvedTailContracts']
    and out['refinement']['temporal']['allPass'] and out['refinement']['fast-gas']['allPass'])
target.write_text(json.dumps(out, separators=(',', ':')) + '\n')
print(json.dumps({k: v for k, v in out.items() if k not in ('cases', 'physicalChecks')}, indent=2))
raise SystemExit(0 if out['qualificationPass'] else 1)
