"""Copy exact retained JSON samples for the browser; no solver/field decoding."""
import hashlib
import json
from pathlib import Path
import tarfile

ROOT = Path(__file__).resolve().parents[1]
ARCHIVE = 'scientific/nonrigid-v98/evidence.tar.gz'
ARCHIVE_SHA = '464d86d0830adf54bb0ce25d631e2ef8a2c4deec24bff6cca51f083f39df8a50'
MEMBER = 'scientific/nonrigid-v98/apparatus-results/predictions.json'
MEMBER_SHA = 'f03f1484f301a397dc8f82ca386d13fcaedf8d874247eee5b8abb11b2371ace6'


def export():
    archive = ROOT / ARCHIVE
    if hashlib.sha256(archive.read_bytes()).hexdigest() != ARCHIVE_SHA:
        raise ValueError('Retained reference archive changed')
    with tarfile.open(archive) as source:
        raw = source.extractfile(MEMBER).read()
    if hashlib.sha256(raw).hexdigest() != MEMBER_SHA:
        raise ValueError('Retained prediction member changed')
    data = json.loads(raw)
    if (data['experimentalQualification'] is not False or
            data['livePlaygroundQualified'] is not False or data['currentFitted'] is not False):
        raise ValueError('Reference scope changed')
    keys = ('scenario', 'anodeCenterM', 'refinement', 'packet', 'packetSHA256',
            'chordVelocityMS', 'experimentalQualification', 'contactVoltageExperimental')
    packet = dict(schemaVersion=1, kind='recorded-argon-reference',
        origin=dict(archive=ARCHIVE, archiveSha256=ARCHIVE_SHA,
                    member=MEMBER, memberSha256=MEMBER_SHA),
        manifest=data['manifest'], scenarios=data['scenarios'],
        cases=[{k: row[k] for k in keys} for row in data['cases']],
        comparisons=data['comparisons'], numericalGates=data['numericalGates'],
        sourceSHA256=data['sourceSHA256'], baselineSHA256=data['baselineSHA256'],
        experimentalQualification=False, livePlaygroundQualified=False, currentFitted=False,
        scope=data['scope'])
    output = (json.dumps(packet, indent=2, allow_nan=False) + '\n').encode()
    (ROOT / 'web-assets/argon-reference/v98.json').write_bytes(output)
    digest = hashlib.sha256(output).hexdigest()
    (ROOT / 'src/argon-reference-identity.ts').write_text(
        '// Generated by scripts/export-argon-reference.py from retained JSON, not a new solve.\n'
        "export const ARGON_REFERENCE_ASSET={url:'/argon-reference/v98.json',\n"
        f" sha256:'{digest}',\n"
        f" archiveSha256:'{ARCHIVE_SHA}',\n"
        f" memberSha256:'{MEMBER_SHA}'}} as const;\n")
    print(f'Copied {len(packet["cases"])} recorded sample sets / {len(output)} bytes / SHA256 {digest}')


if __name__ == '__main__':
    export()
